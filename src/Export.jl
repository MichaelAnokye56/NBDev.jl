"""
Export: notebook cells → real `.jl` library files, the Julia analog of
nbdev's `export.py` (`ExportModuleProc`/`nb_export`) + `maker.py`
(`ModuleMaker`) + the aggregate-`__all__` part of `doclinks.py`
(`nbdev_export`).

Directive handling mirrors nbdev exactly: `#| default_exp name` sets the
notebook's default export target; `#| export`/`#| exports` route a code
cell into that module's file *and* its public name list; `#| exporti`/
`#| exportd` route it into the file but keep it private (excluded from the
aggregated `export` list) — same aliasing nbdev itself uses
(`_exports_,_exportd_ = _export_,_exporti_` in `export.py`). A markdown
cell starting with `# ` (or tagged `#| export`/`#| exportd`) becomes part
of the target module's docstring instead of code.

Unlike nbdev (one notebook → one importable Python submodule, so each
module gets its own `__all__`), a Julia package is conventionally *one*
module with files pulled in via `include()`. So nbjulia aggregates
*every* notebook's public names into one `export` list, written into a
clearly-marked autogenerated block in the package's main file
(`src/<PkgName>.jl`) — see `ARCHITECTURE.md`'s "Where Julia wins" section
for the reasoning.

Known simplifications vs. real nbdev (acceptable for v1, revisit if they
bite): no `_all_`-style explicit override list; tuple-destructuring
assignments (`a, b = 1, 2`) don't contribute names; the module docstring is
every matching markdown cell's text joined, not nbdev's more selective
"H1 + blockquote summary, then `exportd` cells as fenced examples"; and
nbdev's guard skipping a bucket whose code cells are *all* `exportd`
(rather than the whole bucket having no code cells at all, which *is*
replicated via `has_code_cell`) isn't — a narrower edge case for doc-only
buckets that still contain code.
"""
module Export

export nb_export, export_project

using ..NbIO
using ..Process
using ..Config

# ---------------------------------------------------------------------------
# ExportModuleProc: routes cells into per-module buckets
# ---------------------------------------------------------------------------

mutable struct ExportModuleProc <: Process.Processor
    modules::Dict{String,Vector{Any}}
    in_all::Dict{String,Vector{Any}}
    default_exp::Union{Nothing,String}
end
ExportModuleProc() = ExportModuleProc(Dict{String,Vector{Any}}(), Dict{String,Vector{Any}}(), nothing)

function Process.proc_begin!(p::ExportModuleProc)
    empty!(p.modules)
    empty!(p.in_all)
    p.default_exp = nothing
end

function Process.handlers(p::ExportModuleProc)
    exporti_fn = (cell, args...) -> push!(get!(p.modules, isempty(args) ? "#" : String(args[1]), Any[]), cell)
    export_fn = (cell, args...) -> begin
        mod = isempty(args) ? "#" : String(args[1])
        push!(get!(p.modules, mod, Any[]), cell)
        push!(get!(p.in_all, mod, Any[]), cell)
    end
    return Dict{String,Function}(
        "default_exp" => (cell, args...) -> (p.default_exp = String(args[1])),
        "export" => export_fn,
        "exports" => export_fn,
        "exporti" => exporti_fn,
        "exportd" => exporti_fn,
    )
end

"Does `cells` contain at least one code cell? A bucket of markdown-only cells (e.g. `index.ipynb`'s `# Title` cell with no `#| default_exp`) is skipped entirely rather than written or warned about — mirrors nbdev's own guard in `nb_export`."
has_code_cell(cells) = any(c -> get(c, "cell_type", "") == "code", cells)

function Process.on_cell!(p::ExportModuleProc, cell)
    get(cell, "cell_type", "") == "markdown" || return nothing
    src = NbIO.cell_source(cell)
    src === nothing && return nothing
    dirs = NbIO.cell_directives(cell)
    if startswith(strip(src), "# ") || haskey(dirs, "export") || haskey(dirs, "exportd")
        push!(get!(p.modules, "#", Any[]), cell)
    end
    return nothing
end

# ---------------------------------------------------------------------------
# AST walk: what top-level names does a cell's Julia source define?
# ---------------------------------------------------------------------------

"Base identifier a signature/type-expression ultimately names, or `nothing` if it's qualified (`Base.show`) or otherwise not a new local name."
function basename_of(x)
    x isa Symbol && return x
    x isa Expr || return nothing
    h = x.head
    if h in (:curly, :(<:), :call, :(::), :where)
        return basename_of(x.args[1])
    end
    return nothing # e.g. `:.`  (qualified name like `Base.show`) — extends another module's function
end

"""
Every name a (possibly nested) expression `expr` introduces, as a list.
Recurses into `begin...end`/`quote...end` blocks (and their `if`/`for`/
`while`/`let`/`try` relatives below), since grouping several related
`struct`/`abstract type`/`function` defs in one block inside an export
cell is ordinary Julia style, not something nbdev's Python-AST equivalent
ever had to handle (Python has no anonymous block-grouping statement) —
this is one of the few places the Julia port needs *more* cases than the
nbdev original, not fewer.
"""
function toplevel_names(expr)
    expr isa Expr || return String[]
    h = expr.head
    if h in (:block, :quote)
        names = String[]
        for a in expr.args
            a isa LineNumberNode && continue
            append!(names, toplevel_names(a))
        end
        return names
    elseif h === :macrocall
        # `"""doc"""` above a def parses as a @doc macrocall wrapping the real definition.
        return toplevel_names(expr.args[end])
    elseif h === :function || h === :(=)
        nm = basename_of(expr.args[1])
        return nm === nothing ? String[] : [string(nm)]
    elseif h === :const
        return toplevel_names(expr.args[1])
    elseif h === :struct
        nm = basename_of(expr.args[2])
        return nm === nothing ? String[] : [string(nm)]
    elseif h in (:abstract, :primitive)
        nm = basename_of(expr.args[1])
        return nm === nothing ? String[] : [string(nm)]
    elseif h === :macro
        nm = basename_of(expr.args[1])
        return nm === nothing ? String[] : ["@" * string(nm)]
    end
    return String[]
end

"Every top-level expression `src` parses to, in order, stopping silently at the first parse error."
function toplevel_exprs(src::AbstractString)
    exprs = Any[]
    pos, n = 1, lastindex(src)
    while pos <= n
        local expr, newpos
        try
            expr, newpos = Meta.parse(src, pos)
        catch
            break
        end
        expr === nothing && break
        push!(exprs, expr)
        newpos <= pos && break
        pos = newpos
    end
    return exprs
end

"Every top-level name `src` defines, in order."
function toplevel_defined_names(src::AbstractString)
    names = String[]
    for expr in toplevel_exprs(src)
        append!(names, toplevel_names(expr))
    end
    return names
end

"Public names (skipping leading-`_`) that `cells`' code defines, deduplicated, order preserved."
function collect_exported_names(cells)
    names = String[]
    for cell in cells
        get(cell, "cell_type", "") == "code" || continue
        src = NbIO.cell_source(cell)
        src === nothing && continue
        for nm in toplevel_defined_names(src)
            startswith(nm, "_") || push!(names, nm)
        end
    end
    return unique(names)
end

# ---------------------------------------------------------------------------
# Guard: a package must never `using`/`import` itself from its own exported
# code — confirmed empirically to deadlock Julia's package loader (it hangs;
# it does not raise a clean error), so catch it here instead, at export time.
# ---------------------------------------------------------------------------

"Module name(s) a top-level, *non-relative* `using`/`import` clause in `expr` refers to (empty if `expr` isn't one, or every clause is relative, e.g. `.Foo`)."
function imported_package_names(expr)
    expr isa Expr || return String[]
    expr.head in (:using, :import) || return String[]
    names = String[]
    for clause in expr.args
        modexpr = (clause isa Expr && clause.head === :(:)) ? clause.args[1] : clause
        if modexpr isa Expr && modexpr.head === :(.) && length(modexpr.args) == 1 && modexpr.args[1] isa Symbol
            push!(names, string(modexpr.args[1]))
        end
    end
    return names
end

"""
Error clearly if `src` contains a top-level `using`/`import` of `libname`
itself, naming `context` (e.g. a notebook path) in the message.
"""
function check_no_self_import(src::AbstractString, libname::AbstractString, context::AbstractString)
    for expr in toplevel_exprs(src)
        if libname in imported_package_names(expr)
            error(
                "$(context): exported code contains `using/import $(libname)` — this " *
                "makes the package try to import itself while loading, which deadlocks " *
                "Julia's package loader (it hangs; it does not raise a clean error) " *
                "rather than failing cleanly. Functions exported from *other* notebooks " *
                "into the same package are already in scope with no `using` statement " *
                "needed — remove this line from the exported cell. If you need `using " *
                "$(libname)` for interactive use *inside the notebook* (e.g. to try out " *
                "an already-exported function), put it in a separate cell tagged " *
                "`#| hide` instead of `#| export`/`#| exporti`/`#| exports`/`#| exportd`.",
            )
        end
    end
    return nothing
end

# ---------------------------------------------------------------------------
# Writing module files
# ---------------------------------------------------------------------------

"Module docstring text (every matching markdown cell's source, joined) or `\"\"` if none."
function build_docstring(cells)
    parts = String[]
    for cell in cells
        get(cell, "cell_type", "") == "markdown" || continue
        src = NbIO.cell_source(cell)
        src === nothing && continue
        s = strip(src)
        isempty(s) || push!(parts, s)
    end
    isempty(parts) && return ""
    return "\"\"\"\n" * join(parts, "\n\n") * "\n\"\"\"\n"
end

"""
    write_module(cfg, modname, tagged_cells, tagged_in_all)

Write every code cell in `tagged_cells` (a `Vector{Tuple{cell,nbpath}}`,
possibly from several notebooks) to `src/<modname with '.'→'/'>.jl`, each
with a provenance header comment pointing back to its source notebook and
cell id. Returns `(relative_file_path, public_names)`.
"""
function write_module(cfg::Config.NBConfig, modname::String, tagged_cells, tagged_in_all)
    relfile = replace(modname, "." => "/") * ".jl"
    fname = joinpath(cfg.d["src_path"], relfile)

    # Validate every cell *before* touching the file, so a bad cell never
    # leaves behind a half-written/truncated module.
    for (cell, nbpath) in tagged_cells
        get(cell, "cell_type", "") == "code" || continue
        src = NbIO.cell_source(cell)
        src === nothing && continue
        check_no_self_import(src, cfg.lib_name, "$(nbpath) (cell $(get(cell, "id", "?")))")
    end

    mkpath(dirname(fname))
    docstring = build_docstring([c for (c, _) in tagged_cells])
    open(fname, "w") do io
        println(io, "# AUTOGENERATED! DO NOT EDIT!")
        println(io, "# Edit the source notebook(s) below instead, then re-run `export_project()`.")
        println(io)
        isempty(docstring) || println(io, docstring)
        for (cell, nbpath) in tagged_cells
            get(cell, "cell_type", "") == "code" || continue
            src = NbIO.cell_source(cell)
            src === nothing && continue
            body = strip(NbIO.strip_directive_lines(src))
            isempty(body) && continue
            relnb = relpath(abspath(nbpath), dirname(fname))
            println(io, "# %% $(relnb) #$(get(cell, "id", ""))")
            println(io, body)
            println(io)
        end
    end
    names = collect_exported_names([c for (c, _) in tagged_in_all])
    return relfile, names
end

# ---------------------------------------------------------------------------
# Main-module autogenerated include/export block
# ---------------------------------------------------------------------------

const BEGIN_MARK = "# nbjulia: BEGIN AUTOGENERATED EXPORTS (do not edit by hand; run `export_project()`)"
const END_MARK = "# nbjulia: END AUTOGENERATED EXPORTS"

function render_block(includes::Vector{String}, exportnames::Vector{String})
    lines = String[BEGIN_MARK]
    for inc in includes
        push!(lines, "include(\"$(inc)\")")
    end
    isempty(exportnames) || push!(lines, "export " * join(exportnames, ", "))
    push!(lines, END_MARK)
    return join(lines, "\n")
end

"Splice `block` in before the module's closing `end` line (used the first time, before the markers exist)."
function insert_before_closing_end(txt::String, block::String)
    lines = split(txt, '\n')
    idx = findlast(l -> strip(l) == "end", lines)
    idx === nothing && return txt * "\n" * block * "\n"
    return join(vcat(lines[1:(idx - 1)], split(block, '\n'), [""], lines[idx:end]), "\n")
end

function splice_marked_block(txt::String, block::String)
    bstart = findfirst(BEGIN_MARK, txt)
    eend = findlast(END_MARK, txt)
    (bstart === nothing || eend === nothing) && return insert_before_closing_end(txt, block)
    return txt[1:(first(bstart) - 1)] * block * txt[(last(eend) + 1):end]
end

"""
    update_main_module!(mainfile, includes, exportnames)

Rewrite the autogenerated `include(...)`/`export ...` block in `mainfile`
(creating it just before the module's closing `end` the first time),
leaving everything else in the file untouched. If `mainfile` doesn't exist
yet, a minimal `module <Name> ... end` stub is created first (the module
name taken from the file's basename), so this works even before any
scaffolding tool has run. Returns `true` if the file changed.
"""
function update_main_module!(mainfile::String, includes::Vector{String}, exportnames::Vector{String})
    if !isfile(mainfile)
        mkpath(dirname(mainfile))
        modname = first(splitext(basename(mainfile)))
        write(mainfile, "module $(modname)\n\nend\n")
    end
    txt = read(mainfile, String)
    newtxt = splice_marked_block(txt, render_block(includes, exportnames))
    newtxt == txt && return false
    write(mainfile, newtxt)
    return true
end

