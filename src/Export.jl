"""
    nb_export(nbpath; cfg = Config.load_config(dirname(nbpath)))

Export a single notebook's `#| export`/`#| exporti`/... cells into their
target module file(s) under `cfg.src_path`. Does **not** update the main
package module's `include`/`export` block — use `export_project` for that
(or when exporting more than one notebook, since modules can be appended
to across notebooks).
"""
function nb_export(nbpath::AbstractString; cfg::Config.NBConfig = Config.load_config(dirname(nbpath)))
    nb = NbIO.read_nb(nbpath)
    exp = ExportModuleProc()
    Process.process!(Process.NBProcessor(nb, exp))
    written = String[]
    for (mod, cells) in exp.modules
        has_code_cell(cells) || continue
        nm = mod == "#" ? exp.default_exp : mod
        if nm === nothing
            @warn "Notebook '$nbpath' uses `#| export` without a `#| default_exp` cell; skipping."
            continue
        end
        tagged = [(c, nbpath) for c in cells]
        tagged_all = [(c, nbpath) for c in get(exp.in_all, mod, Any[])]
        relfile, _ = write_module(cfg, nm, tagged, tagged_all)
        push!(written, relfile)
    end
    return written
end

"""
    export_project(; cfg = Config.load_config())

Export every notebook under `cfg.nbs_path`, grouping cells by target module
across notebooks (so several notebooks can append to the same module, like
nbdev), then rewrite the main package module's autogenerated
`include(...)`/`export ...` block. Returns `(; relfiles, exportnames)`.
"""
function export_project(; cfg::Config.NBConfig = Config.load_config())
    nbfiles = Config.find_notebooks(cfg)
    all_cells = Dict{String,Vector{Tuple{Any,String}}}()
    all_in_all = Dict{String,Vector{Tuple{Any,String}}}()
    for nbpath in nbfiles
        nb = NbIO.read_nb(nbpath)
        exp = ExportModuleProc()
        Process.process!(Process.NBProcessor(nb, exp))
        for (mod, cells) in exp.modules
            has_code_cell(cells) || continue
            nm = mod == "#" ? exp.default_exp : mod
            if nm === nothing
                @warn "Notebook '$nbpath' uses `#| export` without a `#| default_exp` cell; skipping."
                continue
            end
            append!(get!(all_cells, nm, Tuple{Any,String}[]), [(c, nbpath) for c in cells])
            inall = get(exp.in_all, mod, Any[])
            isempty(inall) || append!(get!(all_in_all, nm, Tuple{Any,String}[]), [(c, nbpath) for c in inall])
        end
    end
    relfiles = String[]
    exportnames = String[]
    for (nm, cells) in all_cells
        relfile, names = write_module(cfg, nm, cells, get(all_in_all, nm, Tuple{Any,String}[]))
        push!(relfiles, relfile)
        append!(exportnames, names)
    end
    sort!(relfiles)
    exportnames = sort!(unique(exportnames))
    mainfile = joinpath(cfg.d["src_path"], cfg.lib_name * ".jl")
    update_main_module!(mainfile, relfiles, exportnames)
    return (; relfiles, exportnames)
end

end # module Export
